# ════════════════════════════════════════════════════════════════════
# 等级估算
# ════════════════════════════════════════════════════════════════════

def estimate_grade_hcl(total_score):
    # 官方区间（中学高华_作文评分标准.pdf）：A1 45-60 / A2 42-44 / B3 39-41
    # B4 36-38 / C5 33-35 / C6 30-32 / 30 以下官方只给 D7-F9,不自行细分
    if total_score >= 45: return "A1"
    if total_score >= 42: return "A2"
    if total_score >= 39: return "B3"
    if total_score >= 36: return "B4"
    if total_score >= 33: return "C5"
    if total_score >= 30: return "C6"
    return "D7-F9"


def estimate_grade_cl(total_score, max_score=40):
    pct = (total_score / max_score) * 100
    if pct >= 75: return "A1"
    if pct >= 70: return "A2"
    if pct >= 65: return "B3"
    if pct >= 60: return "B4"
    if pct >= 55: return "C5"
    if pct >= 50: return "C6"
    if pct >= 45: return "D7"
    if pct >= 40: return "E8"
    return "F9"


def estimate_grade_practical(total_score, max_score=20):
    """实用文 20 分制等级估算(2026-07-06 新增)。
    实用文本身不单独换算 O-Level 等级(会考中与作文合并计入试卷一 80 分),
    此处按百分比给参考等级,口径与 estimate_grade_cl 一致,仅供学生理解水平段。"""
    return estimate_grade_cl(total_score, max_score=max_score)


def grade_distance_hcl(total_score):
    targets_asc = [
        ("C6", 30), ("C5", 33),
        ("B4", 36), ("B3", 39), ("A2", 42), ("A1", 45)
    ]
    for grade, threshold in targets_asc:
        if total_score < threshold:
            return {"next_grade": grade, "points_needed": threshold - total_score}
    return {"next_grade": "已达最高 A1", "points_needed": 0}


def grade_distance_cl(total_score, max_score=40):
    """CL/N(A)/实用文通用(百分比档位,与 estimate_grade_cl 口径一致)。
    2026-07-19 决策:此前只有 HCL 有距离函数,O_CL/N_CL 完全靠 AI 自由文本编,
    是"等级与距离互相矛盾"bug 的根源之一(见 finalize_grade_fields)。"""
    targets_asc = [
        ("E8", 0.40), ("D7", 0.45), ("C6", 0.50), ("C5", 0.55),
        ("B4", 0.60), ("B3", 0.65), ("A2", 0.70), ("A1", 0.75),
    ]
    for grade, pct in targets_asc:
        threshold = round(pct * max_score)
        if total_score < threshold:
            return {"next_grade": grade, "points_needed": threshold - total_score}
    return {"next_grade": "已达最高 A1", "points_needed": 0}


# ════════════════════════════════════════════════════════════════════
# 2026-07-19 决策(刘老师核定): grade_estimate / grade_distance 由代码强制统一
# ────────────────────────────────────────────────────────────────────
# 根因: 此前这两个字段都是 AI 自由文本,互相之间、与 scores.total 之间都没有
# 任何校验,曾出现"等级 A1、却说距离 B3 还差 3-5 分"这种不可能同时成立的矛盾
# (A1 是最高档,不可能同时"还差着够不到 B3")。O_CL/N_CL 更严重:压根没有
# 确定性距离函数,AI 报出的"总分 33-35"这类数字甚至可能是从 HCL 60 分制的
# 例句里抄来的,套在 40 分制里毫无意义。
# 修法: 批改结果解析成功后,用本函数强制用 scores.total 重新计算
# grade_estimate 和 grade_distance 的"下一档+还差几分"部分,只保留 AI 给的
# 具体改进建议文字(纯建议,不再让 AI 自己报等级名称和分数差)。
# 配套: JSON 输出格式里 grade_distance 的说明已改为"只写怎么改进,不要写
# 等级名称或分数差距"(见本文件 GRADING_PHILOSOPHY 之后的输出格式段)。
# ════════════════════════════════════════════════════════════════════
def finalize_grade_fields(feedback, exam_level):
    """服务端强制统一等级字段(双保险,任何异常绝不拖垮主批改流程)。
    两处引擎(学生版 pages/student.py、教师版 grading_engine.py)在解析出
    feedback JSON 后、存库前必须调用本函数。"""
    try:
        scores = feedback.get("scores")
        if not isinstance(scores, dict):
            return feedback
        total = scores.get("total")
        if not isinstance(total, (int, float)):
            c, l = scores.get("content"), scores.get("language")
            if isinstance(c, (int, float)) and isinstance(l, (int, float)):
                total = c + l
            else:
                return feedback

        cfg = EXAM_LEVELS.get(exam_level, {})
        essay_max = cfg.get("essay_total", 40)
        is_practical = exam_level.startswith("PRACTICAL")

        # ── 内容闸门·代码级强制封顶 (v6.8 2026-07-19 / v6.9 2026-07-21 刘老师裁定) ──
        # prompt 规则 AI 可能不执行;这里按 AI 自己填的 content_gate/scores 由代码执行,
        # 想绕都绕不过。v6.9(任务#7全班校准)新增三项:
        #   ① 错字独立扣分(方案A,总分公式不变):
        #      language = language_band − min(3, 0.5×错字数);错字数与 red_issues
        #      错别字条数取大者(漏报不能降低扣分);非 30 分制按 language_max/30 折算
        #   ② core_detail_extent 占比枚举推严重度(只升不降):
        #      几乎没有→严重 / 仅一小段→至少较严重(五面长文占比低照样触发;
        #      免罚线"两段以上较长"由 prompt 约束,代码方向只升不降,不会误伤)
        #   ③ 内容硬伤联动语文顶:严重→语文≤第2下顶(19/12/6),
        #      较严重→语文≤第2上顶(23/16/8) — 19号/02号校准案例
        caps_note = []
        content_max = cfg.get("content_max", 20)
        language_max = cfg.get("language_max", 20)

        # ① 错字扣分强制重算(AI 未输出 language_band 时跳过,兼容旧格式)
        l_band = scores.get("language_band")
        t_cnt = scores.get("typo_count")
        red_typos = 0
        try:
            for _p in (feedback.get("paragraph_feedback") or []):
                for _ri in (_p.get("red_issues") or []):
                    _t = str(_ri.get("type", ""))
                    if "错" in _t and "病" not in _t and "标点" not in _t:
                        red_typos += 1
        except Exception:
            red_typos = 0
        if isinstance(t_cnt, (int, float)) and t_cnt >= 0:
            t_cnt = max(int(t_cnt), red_typos)
        else:
            t_cnt = red_typos
        if isinstance(l_band, (int, float)):
            _scale = language_max / 30.0  # 非HCL等比折算(待普华批次校准复核)
            _ded = min(3.0 * _scale, 0.5 * _scale * t_cnt)
            _new_l = int(l_band - _ded + 0.5)  # 四舍五入(.5 进位)
            _new_l = max(0, min(_new_l, language_max))
            if scores.get("language") != _new_l:
                caps_note.append("语文 %s→%s(档位分%s−错字%s个×0.5,封顶3)"
                                 % (scores.get("language"), _new_l,
                                    l_band, t_cnt))
            scores["language"] = _new_l

        gate = feedback.get("content_gate")
        if isinstance(gate, dict):
            c = scores.get("content")
            lvl = str(gate.get("c_level") or "无").strip()
            flags_bad = (any(gate.get(k) is False for k in
                             ("life_logic_ok", "detail_balance_ok",
                              "keyword_focus_ok"))
                         or gate.get("keyword_misread") is True)
            if lvl == "无" and flags_bad:
                lvl = "较严重"   # 闸门自相矛盾:就严不就宽
            # ② v6.9 占比枚举 → 严重度只升不降
            extent = str(gate.get("core_detail_extent") or "").strip()
            if extent == "几乎没有":
                lvl = "严重"
            elif extent == "仅一小段" and lvl != "严重":
                lvl = "较严重"
            cap = None
            lang_cap = None
            if lvl == "严重":
                cap = {30: 14, 20: 9, 10: 4}.get(content_max,
                                                 int(content_max * 0.45))
                lang_cap = {30: 19, 20: 12, 10: 6}.get(language_max,
                                                       int(language_max * 0.64))
            elif lvl == "较严重":
                # 2026-08-11 决策(刘老师裁定「不太切题、详略不当 → 内容不超过16」):
                # 作文侧内容顶 18→16(HCL,第2下偏下)、12→11(普华,第2等偏下)。
                # 实用文维持 6 不动 —— 实用文另有切题三级表(不太切合题意 ≤5)已更严,
                # 本次裁定针对作文,不擅自扩大到实用文(如需收紧，另行裁定)。
                cap = {30: 16, 20: 11, 10: 6}.get(content_max,
                                                  int(content_max * 0.55))
                lang_cap = {30: 23, 20: 16, 10: 8}.get(language_max,
                                                       int(language_max * 0.77))
            if (cap is not None and isinstance(c, (int, float)) and c > cap):
                caps_note.append("内容 %s→%s(C级%s:%s)"
                                 % (c, cap, lvl, gate.get("reason") or ""))
                c = cap
                scores["content"] = c

            # ── 2026-08-11 决策: 分论点关键词轴「脱轴」三档封顶(议论文专用) ──
            # 病症: 学生提出分论点后,阐述部分完全没围绕该分论点的关键词展开
            # (换轴/空转/例不对轴/贴标签)。旧规则只查题目关键词和 PEEL 有没有,
            # 查不出「人来了但干的是别的活」,故新增段级证据字段 sub_point_axis。
            # AI 只负责逐段如实报 verdict,封顶一律由代码执行(v6.8 教训: prompt
            # 写了 AI 也会口头承认却照给高分)。记叙文/实用文该字段为空数组,不触发。
            axis = gate.get("sub_point_axis")
            if isinstance(axis, list) and len(axis) > 0:
                _total_sp = len(axis)
                _off = 0
                for _it in axis:
                    if isinstance(_it, dict):
                        if str(_it.get("verdict") or "").strip() not in ("紧扣", ""):
                            _off += 1
                if _off > 0:
                    if _off >= _total_sp:          # 全部脱轴 → 不及格
                        a_cap = {30: 12, 20: 8}.get(content_max, None)
                        a_tag = "全部脱轴"
                    elif _off * 2 > _total_sp:     # 一半以上脱轴
                        a_cap = {30: 14, 20: 9}.get(content_max, None)
                        a_tag = "过半脱轴"
                    else:                          # 仅个别段脱轴
                        a_cap = {30: 16, 20: 11}.get(content_max, None)
                        a_tag = "个别段脱轴"
                    c2 = scores.get("content")
                    if (a_cap is not None and isinstance(c2, (int, float))
                            and c2 > a_cap):
                        caps_note.append("内容 %s→%s(分论点%s %s/%s段)"
                                         % (c2, a_cap, a_tag, _off, _total_sp))
                        scores["content"] = a_cap
                    # 脱轴 = 未紧扣关键词,严重度并入 C 级通道以带动语文联动顶;
                    # 只升不降,已判「严重」的不回退
                    if lvl != "严重":
                        lvl = "严重" if _off >= _total_sp else "较严重"
                        lang_cap = ({30: 19, 20: 12}.get(language_max)
                                    if lvl == "严重"
                                    else {30: 23, 20: 16}.get(language_max))
            # ③ v6.9 内容硬伤联动语文顶(在错字扣分之后应用,顶住最终语文分)
            l = scores.get("language")
            if (lang_cap is not None and isinstance(l, (int, float))
                    and l > lang_cap):
                caps_note.append("语文 %s→%s(内容硬伤%s·联动顶)"
                                 % (l, lang_cap, lvl))
                scores["language"] = lang_cap
            if (gate.get("ending_lyric_ok") is False and not is_practical
                    and isinstance(scores.get("content"), (int, float))
                    and isinstance(scores.get("language"), (int, float))):
                c = scores["content"]
                l = scores["language"]
                tcap = 44 if exam_level == "HCL" else 29
                if c + l > tcap:
                    caps_note.append("总分 %s→%s(记叙文无结尾抒情议论)"
                                     % (c + l, tcap))
                    scores["content"] = max(0, c - (c + l - tcap))
        if (isinstance(scores.get("content"), (int, float))
                and isinstance(scores.get("language"), (int, float))):
            scores["total"] = scores["content"] + scores["language"]
            total = scores["total"]
        if caps_note:
            feedback["auto_caps"] = caps_note

        if exam_level == "HCL":
            grade = estimate_grade_hcl(total)
            dist = grade_distance_hcl(total)
        elif is_practical:
            grade = estimate_grade_practical(total, max_score=essay_max)
            dist = grade_distance_cl(total, max_score=essay_max)
        else:  # O_CL / N_CL
            grade = estimate_grade_cl(total, max_score=essay_max)
            dist = grade_distance_cl(total, max_score=essay_max)

        advice = (feedback.get("grade_distance") or "").strip()
        if dist["points_needed"] <= 0:
            lead = "已达本次评估的最高等级。"
        else:
            lead = f"距离{dist['next_grade']}还差约{dist['points_needed']}分。"
        feedback["grade_estimate"] = grade
        feedback["grade_distance"] = (lead + advice) if advice else lead
    except Exception:
        pass  # 与语文分下限钳位同一纪律:计算异常绝不拦批改主流程
    return feedback


