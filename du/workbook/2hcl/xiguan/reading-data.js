export function gradeReadingTask(task, answer) {
  if (!task) return false;
  if (task.type === "choice") return Number(answer) === Number(task.answer);
  if (!Array.isArray(answer) || !Array.isArray(task.answer)) return false;
  const actual = task.type === "multi"
    ? [...answer].map(Number).sort((a, b) => a - b)
    : answer.map(Number);
  const expected = task.type === "multi"
    ? [...task.answer].map(Number).sort((a, b) => a - b)
    : task.answer.map(Number);
  return actual.length === expected.length && actual.every((value, index) => value === expected[index]);
}
